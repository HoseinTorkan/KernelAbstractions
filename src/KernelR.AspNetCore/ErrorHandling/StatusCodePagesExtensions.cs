using KernelR.Patterns.Results;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;

namespace KernelR.AspNetCore.ErrorHandling;

/// <summary>
/// Provides extension methods for configuring status code pages.
/// </summary>
public static class StatusCodePagesExtensions
{
    /// <summary>
    /// Configures the application to return a standardized <see cref="ProblemDetails"/>
    /// response for HTTP status codes between 400 and 599 that do not have a body.
    /// </summary>
    /// <remarks>
    /// <para>
    /// This covers responses generated by the framework itself (routing 404, authentication
    /// 401, authorization 403, method-not-allowed 405, etc.) that would otherwise be empty.
    /// Responses produced by <c>KernelModelStateFilter</c>, <c>KernelRExceptionHandler</c>,
    /// or any endpoint that writes its own body are <b>not</b> affected, because
    /// <c>UseStatusCodePages</c> only runs when the response body is empty.
    /// </para>
    /// <para>
    /// The reported <see cref="ProblemDetails.Status"/> is always the original HTTP status
    /// code, never a value derived from <see cref="ErrorType"/>. This preserves statuses
    /// such as 405 that have no direct <see cref="ErrorType"/> equivalent.
    /// </para>
    /// </remarks>
    /// <param name="app">The <see cref="IApplicationBuilder"/> instance.</param>
    /// <returns>The same <see cref="IApplicationBuilder"/> instance for chaining.</returns>
    public static IApplicationBuilder UseKernelStatusCodePages(this IApplicationBuilder app)
    {
        return app.UseStatusCodePages(async context =>
        {
            HttpContext httpContext = context.HttpContext;
            int statusCode = httpContext.Response.StatusCode;

            ErrorType errorType = statusCode switch
            {
                401 => ErrorType.Unauthorized,
                403 => ErrorType.Forbidden,
                404 => ErrorType.NotFound,
                405 => ErrorType.InvalidInput,
                _ => ErrorType.Infrastructure
            };

            Error error = new(
                $"KernelR.Http.{statusCode}",
                $"The request failed with status code {statusCode}.",
                errorType);

            ProblemDetails problemDetails = new()
            {
                // Use the original status code, not a value derived from ErrorType,
                // so statuses such as 405 are preserved.
                Type = $"https://httpstatuses.io/{statusCode}",
                Title = error.Code,
                Detail = error.Text,
                Status = statusCode,
                Instance = httpContext.Request.Path
            };

            problemDetails.Extensions["traceId"] = httpContext.TraceIdentifier;
            problemDetails.Extensions["timestamp"] = DateTimeOffset.UtcNow;
            problemDetails.Extensions["errorType"] = error.ErrorType.ToString();

            await httpContext.Response.WriteAsJsonAsync(
                problemDetails,
                options: null,
                contentType: "application/problem+json");
        });
    }
}
